// ─────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────

export function getRegionTheme(id: string): RegionTheme {
  const theme = REGION_THEMES[id];
  if (!theme) {
    console.warn(`[DocSaathi] Unknown region id "${id}", falling back to default.`);
    return DEFAULT_REGION;
  }
  return theme;
}

